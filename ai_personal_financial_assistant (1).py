from transformers import pipeline

import torch
device = 0 if torch.cuda.is_available() else -1

nlp = pipeline(
    "sentiment-analysis",
    model="ProsusAI/finbert",
    device=device
)

def analyze_sentiment(df, text_column='title', batch_size=16):
    df = df.copy()

    # Clean text
    texts = df[text_column].fillna('').astype(str).tolist()

    # Run model (FAST)
    results = nlp(
        texts,
        batch_size=batch_size,
        truncation=True,
        max_length=128
    )

    # Extract results
    df['sentiment'] = [res['label'].lower() for res in results]
    df['confidence'] = [res['score'] for res in results]

    return df

# Run
