import yfinance as yf
import pandas as pd

def get_ticker_news(ticker_symbol):
    ticker = yf.Ticker(ticker_symbol)
    news = ticker.news

    data = []
    for item in news:
        data.append({
            'title': item.get('title'),
            'publisher': item.get('publisher'),
            'link': item.get('link')
        })

    return pd.DataFrame(data)

